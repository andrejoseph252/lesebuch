// The book itself always stays German — only the app's buttons and messages switch.
import { settings } from './settings.js';

/** Translate a UI string; {0}, {1}… are filled from args. */
export function t(key, ...args) {
  const s = settings.uiLang === 'de' ? key : (EN[key] ?? key);
  return args.length ? s.replace(/\{(\d)\}/g, (_, i) => args[i]) : s;
}
